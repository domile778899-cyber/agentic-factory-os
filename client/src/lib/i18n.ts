export type TranslationKey = keyof typeof translations.zh;

let currentLocale: Locale = (() => {
  try { return (localStorage.getItem('locale') as Locale) || 'zh'; }
  catch { return 'zh'; }
})();

export function getLocale(): Locale { return currentLocale; }

export function setLocale(locale: Locale) {
  currentLocale = locale;
  try { localStorage.setItem('locale', locale); }
  catch {}
  // Set RTL direction for Arabic
  if (typeof document !== 'undefined') {
    document.documentElement.dir = LOCALE_NAMES[locale]?.dir || 'ltr';
    document.documentElement.lang = locale;
  }
  window.dispatchEvent(new CustomEvent('locale-change', { detail: locale }));
}

export function t(key: TranslationKey): string {
  const localeTranslations = translations[currentLocale] as Record<string, string>;
  const fallback = translations.zh as Record<string, string>;
  return localeTranslations[key] || fallback[key] || key;
}
